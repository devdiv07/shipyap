@dataclass(frozen=True)
class _Located:
    """A located source reference: the real cited text (NFC) and its normalized form, each with
    the cited spans. Without a quote the span is the whole range. With one, the spans are where
    the normalized quote occurs. A quote only selects spans: evidence is read from the source
    text inside them, never from the drafter's quote. Patterns run over the whole cited text and
    only matches lying entirely inside a span count, so the source's own word and number
    boundaries apply ("45" inside "453" is not 45; "I" inside "Is" is not first person)."""

    text: str
    spans: tuple[tuple[int, int], ...]
    canonical: str
    canonical_spans: tuple[tuple[int, int], ...]


@dataclass(frozen=True)
class _Evidence:
    refs: tuple[CheckedSourceRef, ...]
    authors: tuple[CheckedAuthorRef, ...]
    located: tuple[_Located, ...]

    @property
    def author_texts(self) -> list[str]:
        return [author.text for author in self.authors if author.text is not None]

    def numbers(self) -> set[str]:
        source = {
            _number_token(literal)
            for located in self.located
            for literal in _phrases(located.text, _NUMBER, located.spans)
        }
        return source | {token for text in self.author_texts for token in number_tokens(text)}

    def source_words(self, patterns: tuple[re.Pattern[str], ...]) -> set[str]:
        return {
            word
            for located in self.located
            for word in _words(located.canonical, patterns, located.canonical_spans)
        }

    def source_has_phrase(self, phrase: str, pattern: re.Pattern[str]) -> bool:
        wanted = normalize(phrase).casefold()
        return any(
            normalize(found).casefold() == wanted
            for located in self.located
            for found in _phrases(located.canonical, pattern, located.canonical_spans)
        )

    def spelled_numbers(self) -> set[str]:
        source = {
            word.casefold()
            for located in self.located
            for word in _phrases(located.canonical, _SPELLED_NUMBER, located.canonical_spans)
        }
        return source | {
            word.casefold()
            for text in self.author_texts
            for word in _phrases(text, _SPELLED_NUMBER)
        }


def _evidence(segment: Segment, brief: Brief, items: dict[str, str]) -> _Evidence:
    refs = tuple(_check_ref(ref, brief) for ref in segment.source_refs)
    located = tuple(
        found
        for raw, checked in zip(segment.source_refs, refs, strict=True)
        if (found := _locate(raw, checked)) is not None
    )
    authors = tuple(CheckedAuthorRef(id=ref, text=items.get(ref)) for ref in segment.author_refs)
    return _Evidence(refs=refs, authors=authors, located=located)


def _prose(text: str) -> str:
    # Links and hashtags are checked on their own; their characters (a "07" in a repository URL)
    # are not claims, so every other rule reads the prose without them.
    return _HASHTAG.sub(" ", _LINK.sub(" ", text))


def _check_segment(
    segment: Segment,
    brief: Brief,
    evidence: _Evidence,
    comparisons: list[Finding],
    known_labels: frozenset[tuple[str, str]],
    statement: bool,
) -> SegmentRecord:
    findings: list[Finding] = []
    refs, authors = evidence.refs, evidence.authors
    for ref in refs:
        code = _REF_FINDINGS.get(ref.ref_check)
        if code is not None:
            findings.append(
                _finding(code, segment.id, f"{ref.path}:{ref.line_start}-{ref.line_end}")
            )
    for author in authors:
        if author.text is None:
            findings.append(_finding(FindingCode.AUTHOR_REF_NOT_FOUND, segment.id, author.id))
        elif is_tool_item(author.text):
            findings.append(_finding(FindingCode.TOOL_ITEM_CITED, segment.id, author.id))

    prose = _prose(segment.text)
    cited = {ref.path for ref in segment.source_refs}
    files = ["\n".join(s.lines) for s in brief.sources if s.path in cited]
    numeric = mask_known_ids(prose, files)  # a hash the cited file holds is a name, not a count
    available = evidence.numbers()
    claimed = claim_numbers(numeric)
    unknown_labels = {token for word, token in labels(numeric) if (word, token) not in known_labels}
    numbers = tuple(
        CheckedNumber(
            token=token,
            located=token in available or (token not in claimed and token not in unknown_labels),
        )
        for token in number_tokens(numeric)
    )
    missing = [number.token for number in numbers if not number.located]
    if missing:
        findings.append(
            _finding(FindingCode.NUMBER_NOT_IN_EVIDENCE, segment.id, ", ".join(missing))
        )

    author_recorded = brief.contribution.author_name != UNRECORDED_AUTHOR
    findings += _first_person(segment.id, prose, evidence, author_recorded, statement)
    findings += comparisons  # judged on the rendered paragraph; see _comparison_findings
    findings += _hashtags_and_links(segment, brief)
    findings += _style(segment.id, prose, evidence)
    findings += _tool_terms(segment.id, prose, files)
    if author_recorded and segment.basis == Basis.AUTHOR:
        findings += _author_basis(segment.id, prose, evidence)

    classification = _classify(segment.basis, findings)
    questions = REVIEW_QUESTIONS if author_recorded else UNRECORDED_REVIEW_QUESTIONS
    return SegmentRecord(
        id=segment.id,
        paragraph_break_before=segment.paragraph_break_before,
        text=segment.text,
        declared_basis=segment.basis,
        classification=classification,
        review_question=questions[classification],
        source_refs=refs,
        author_refs=authors,
        numbers=numbers,
        findings=tuple(findings),
    )


_CLASSIFICATION = {
    Basis.SOURCE: Classification.SOURCE_REFERENCED,
    Basis.AUTHOR: Classification.AUTHOR_STATED,
    Basis.INTERPRETATION: Classification.INTERPRETATION,
    Basis.FRAMING: Classification.FRAMING,
}


def _classify(basis: Basis, findings: Iterable[Finding]) -> Classification:
    """UNSUPPORTED when anything blocks; INTERPRETATION for an AUTHOR segment that cites none
    of the author's own statements (AUTHOR_RECLASSIFIED); otherwise the declared basis."""
    findings = list(findings)
    if any(finding.severity == Severity.BLOCKING for finding in findings):
        return Classification.UNSUPPORTED
    if any(finding.code == FindingCode.AUTHOR_RECLASSIFIED for finding in findings):
        return Classification.INTERPRETATION
    return _CLASSIFICATION[basis]


_REF_FINDINGS = {
    RefCheck.PATH_NOT_IN_SNAPSHOT: FindingCode.REF_PATH_NOT_IN_SNAPSHOT,
    RefCheck.RANGE_INVALID: FindingCode.REF_RANGE_INVALID,
    RefCheck.QUOTE_NOT_FOUND: FindingCode.REF_QUOTE_NOT_FOUND,
}


def _check_ref(ref: SourceRef, brief: Brief) -> CheckedSourceRef:
    source = brief.source(ref.path)
    common = {
        "path": ref.path,
        "line_start": ref.line_start,
        "line_end": ref.line_end,
        "quote": ref.quote,
        "url": brief.snapshot.source_url,
        "revision_sha": brief.snapshot.revision_sha,
    }
    if source is None:
        return CheckedSourceRef(
            **common,
            file_sha256=None,
            file_label=None,
            ref_check=RefCheck.PATH_NOT_IN_SNAPSHOT,
            excerpt=(),
        )
    if ref.line_end > len(source.lines):
        check, excerpt = RefCheck.RANGE_INVALID, ()
    else:
        excerpt = source.lines[ref.line_start - 1 : ref.line_end]
        if ref.quote is None:
            check = RefCheck.RANGE_CITED
        else:
            quote = normalize(ref.quote)
            located = bool(quote) and quote in normalize("\n".join(excerpt))
            check = RefCheck.QUOTE_LOCATED if located else RefCheck.QUOTE_NOT_FOUND
    return CheckedSourceRef(
        **common,
        file_sha256=source.sha256,
        file_label="SOURCE_MATCH",
        ref_check=check,
        excerpt=excerpt,
    )


def _locate(ref: SourceRef, checked: CheckedSourceRef) -> _Located | None:
    if checked.ref_check not in LOCATED:
        return None
    text = unicodedata.normalize("NFC", "\n".join(checked.excerpt))
    canonical, offsets = _canonical(text)
    if ref.quote is None:
        return _Located(text, ((0, len(text)),), canonical, ((0, len(canonical)),))
    quote = normalize(ref.quote)  # non-empty and present: _check_ref located it
    spans: list[tuple[int, int]] = []
    canonical_spans: list[tuple[int, int]] = []
    start = canonical.find(quote)
    while start >= 0:
        end = start + len(quote)
        canonical_spans.append((start, end))
        spans.append((offsets[start], offsets[end - 1] + 1))
        start = canonical.find(quote, start + 1)
    return _Located(text, tuple(spans), canonical, tuple(canonical_spans))


def has_statement(brief: Brief) -> bool:
    """Whether the repository's author recorded their own statement (`attempted` items written
    by them, not labelled backlog text)."""
    contribution = brief.contribution
    return contribution.author_name != UNRECORDED_AUTHOR and any(
        not text.startswith(UNVERIFIED_PREFIX) for text in contribution.attempted
    )


def _first_person(
    segment_id: str, prose: str, evidence: _Evidence, author_recorded: bool, statement: bool
) -> list[Finding]:
    found = _words(prose, _FIRST_PERSON)
    if not found:
        return []
    if not author_recorded:
        # A generated contribution: its items are labelled backlog text and a source's own "we"
        # is its authors', so nothing a segment cites makes the post's first person anyone's.
        return [_finding(FindingCode.FIRST_PERSON_UNATTRIBUTED, segment_id, ", ".join(found))]
    # Only the author's own statements license "I": items labelled as unverified backlog text
    # (an angle or support a model proposed) are not anyone's statement.
    if any(not text.startswith(UNVERIFIED_PREFIX) for text in evidence.author_texts):
        return []
    in_source = evidence.source_words(_FIRST_PERSON)
    unattributed = [word for word in found if word not in in_source]
    if not unattributed:
        return []
    # The author's statement exists but this segment does not cite it: the owner reads the
    # sentence beside the statement (a warning), instead of the draft being blocked.
    code = (
        FindingCode.FIRST_PERSON_FROM_STATEMENT
        if statement
        else (FindingCode.FIRST_PERSON_UNATTRIBUTED)
    )
    return [_finding(code, segment_id, ", ".join(unattributed))]


def _author_basis(segment_id: str, prose: str, evidence: _Evidence) -> list[Finding]:
    """An AUTHOR segment speaks as the author, so it must cite at least one of the author's own
    statements; the backlog angle (`insight`) and tool items are not their words. Without one, a
    first-person sentence is blocked (it puts the angle in the author's mouth); any other is
    treated as the drafter's INTERPRETATION, with a warning."""
    texts = evidence.author_texts
    if any(is_own_statement(text) for text in texts) or (texts and all(map(is_tool_item, texts))):
        return []  # an author statement is cited, or only tool items (blocked on their own)
    code = (
        FindingCode.AUTHOR_NOT_STATEMENT
        if _words(prose, _FIRST_PERSON)
        else FindingCode.AUTHOR_RECLASSIFIED
    )
    return [_finding(code, segment_id, ", ".join(author.id for author in evidence.authors))]


def _tool_terms(segment_id: str, prose: str, files: list[str]) -> list[Finding]:
    """The tool's vocabulary in a post: phrases block, single words warn. Either is fine when a
    file the segment cites uses the same words (the repository's own subject)."""
    held = _SPACE.sub(" ", "\n".join(unicodedata.normalize("NFC", f) for f in files)).casefold()
    text = unicodedata.normalize("NFC", prose)
    phrases = list(_TOOL_PHRASE.finditer(text))
    findings = []
    blocked = [m.group() for m in phrases if _SPACE.sub(" ", m.group()).casefold() not in held]
    if blocked:
        detail = ", ".join(dict.fromkeys(blocked))
        findings.append(_finding(FindingCode.TOOL_PHRASE, segment_id, detail))
    rest = text
    for m in phrases:  # a word inside a phrase is judged with the phrase
        rest = rest[: m.start()] + " " * (m.end() - m.start()) + rest[m.end() :]
    words = [
        m.group()
        for m in _TOOL_WORD.finditer(rest)
        if not re.search(rf"\b{re.escape(m.group().casefold())}\b", held)
    ]
    if words:
        detail = ", ".join(dict.fromkeys(words))
        findings.append(_finding(FindingCode.TOOL_WORD, segment_id, detail))
    return findings


def _comparison_findings(
    segments: Iterable[Segment], evidence: dict[str, _Evidence]
) -> dict[str, list[Finding]]:
    """Comparisons are detected in each rendered paragraph, because the drafter controls segment
    boundaries: "This method is better" + "than existing tools." renders as one comparison. A
    match is attributed to every segment it overlaps, and only those segments' evidence can
    support it, under the single-segment rule. The phrase must be in their located source text,
    or (a warning) in their cited contributor items; otherwise it is blocking."""
    found: dict[str, list[Finding]] = {}
    for paragraph in _paragraphs(segments):
        bounds: list[tuple[int, int, str]] = []
        pieces: list[str] = []
        cursor = 0
        for segment in paragraph:
            prose = _prose(segment.text)
            bounds.append((cursor, cursor + len(prose), segment.id))
            pieces.append(prose)
            cursor += len(prose) + 1  # segments render joined by one space
        rendered = " ".join(pieces)
        for match in _COMPARISON.finditer(rendered):
            ids = [sid for start, end, sid in bounds if start < match.end() and end > match.start()]
            phrase = match.group()
            if any(evidence[sid].source_has_phrase(phrase, _COMPARISON) for sid in ids):
                continue
            attributed = any(_contains_phrase(evidence[sid].author_texts, phrase) for sid in ids)
            code = (
                FindingCode.COMPARISON_ATTRIBUTED
                if attributed
                else FindingCode.COMPARISON_UNSUPPORTED
            )
            detail = phrase if len(ids) == 1 else f"{phrase} (rendered across {', '.join(ids)})"
            for sid in ids:
                finding = _finding(code, sid, detail)
                if finding not in found.setdefault(sid, []):
                    found[sid].append(finding)
    return found


def _hashtags_and_links(segment: Segment, brief: Brief) -> list[Finding]:
    allowed = {tag.casefold() for tag in brief.contribution.hashtags}
    findings = [
        _finding(FindingCode.HASHTAG_NOT_ALLOWED, segment.id, tag)
        for tag in _phrases(segment.text, _HASHTAG)
        if tag.casefold() not in allowed
    ]
    for match in _LINK.finditer(segment.text):
        link = match.group().rstrip(_TRAILING_PUNCTUATION)
        if link != brief.snapshot.source_url:
            findings.append(_finding(FindingCode.LINK_NOT_ALLOWED, segment.id, link))
    return findings


def _style(segment_id: str, prose: str, evidence: _Evidence) -> list[Finding]:
    findings = [
        _finding(FindingCode.PROMOTIONAL_LANGUAGE, segment_id, phrase.strip())
        for phrase in _phrases(prose, _PROMOTIONAL)
    ]
    evidence_words = evidence.spelled_numbers()
    unlocated = [
        word for word in _phrases(prose, _SPELLED_NUMBER) if word.casefold() not in evidence_words
    ]
    if unlocated:
        findings.append(_finding(FindingCode.SPELLED_NUMBER, segment_id, ", ".join(unlocated)))
    if _MARKDOWN.search(prose):
        findings.append(_finding(FindingCode.MARKDOWN_SYNTAX, segment_id))
    return findings


# --- whole post ------------------------------------------------------------------------------


def _document_findings(
    response: DraftResponse,
    records: tuple[SegmentRecord, ...],
    questions: tuple[CheckedQuestion, ...],
    post: str,
    limitation_cited: bool = False,
) -> tuple[Finding, ...]:
    if not records:
        return ()
    findings = []
    if len(post) > MAX_POST_CHARS:
        findings.append(_finding(FindingCode.POST_TOO_LONG, None, str(len(post))))
    cited = {ref for segment in response.segments for ref in segment.author_refs}
    if "insight" not in cited:
        findings.append(_finding(FindingCode.NO_INSIGHT_REFERENCE, None))
    if not any(r.classification == Classification.SOURCE_REFERENCED for r in records):
        findings.append(_finding(FindingCode.NO_SOURCE_REFERENCE, None))
    if not limitation_cited:
        findings.append(_finding(FindingCode.NO_LIMITATION_REFERENCE, None))
    for question in questions:
        for ref in question.source_refs:
            if ref.ref_check not in LOCATED:
                detail = f"{ref.path}:{ref.line_start}-{ref.line_end}"
                findings.append(_finding(FindingCode.VERIFICATION_REF_INVALID, None, detail))
    return tuple(findings)


# --- helpers ---------------------------------------------------------------------------------


def _finding(code: FindingCode, segment_id: str | None, detail: str | None = None) -> Finding:
    severity = Severity.BLOCKING if code in BLOCKING else Severity.WARNING
    return Finding(
        code=code, severity=severity, segment_id=segment_id, message=MESSAGES[code], detail=detail
    )


Spans = tuple[tuple[int, int], ...]


def _phrases(text: str, pattern: re.Pattern[str], spans: Spans | None = None) -> list[str]:
    """Distinct matches in order. With `spans`, only matches lying entirely inside one span.
    Matching always runs over the whole text, so boundaries are the text's own."""
    found: list[str] = []
    for match in pattern.finditer(text):
        if spans is not None and not any(
            start <= match.start() and match.end() <= end for start, end in spans
        ):
            continue
        if match.group() not in found:
            found.append(match.group())
    return found


def _words(
    text: str, patterns: tuple[re.Pattern[str], ...], spans: Spans | None = None
) -> list[str]:
    found: list[str] = []
    for pattern in patterns:
        for match in _phrases(text, pattern, spans):
            word = match if match == "I" else match.casefold()
            if word not in found:
                found.append(word)
    return found


def _contains_phrase(texts: list[str], phrase: str) -> bool:
    wanted = normalize(phrase).casefold()
    return any(wanted in normalize(text).casefold() for text in texts)
