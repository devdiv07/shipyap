def normalize(text: str) -> str:
    return _canonical(text)[0]


def _canonical(text: str) -> tuple[str, tuple[int, ...]]:
    """The normalized form used for quote matching, plus each output character's index in
    NFC(text): NFC; blockquote markers stripped from each line; lines joined by one space;
    `* _ \\`` removed; whitespace runs collapsed to one space; outer whitespace stripped."""
    text = unicodedata.normalize("NFC", text)
    kept: list[tuple[str, int]] = []
    start = 0
    for number, line in enumerate(text.split("\n")):
        if number:
            kept.append((" ", start - 1))  # the line break itself becomes the joining space
        prefix = _QUOTE_PREFIX.match(line)
        skip = prefix.end() if prefix else 0
        kept += [
            (char, start + index)
            for index, char in enumerate(line)
            if index >= skip and not _EMPHASIS.match(char)
        ]
        start += len(line) + 1
    chars: list[str] = []
    offsets: list[int] = []
    for char, index in kept:
        if _SPACE.match(char):
            if not chars or chars[-1] == " ":
                continue
            char = " "
        chars.append(char)
        offsets.append(index)
    if chars and chars[-1] == " ":
        chars.pop()
        offsets.pop()
    return "".join(chars), tuple(offsets)


def _number_token(literal: str) -> str:
    whole, dot, fraction = literal.replace(",", "").partition(".")
    return (whole.lstrip("0") or "0") + dot + fraction


def number_tokens(text: str) -> tuple[str, ...]:
    """Digit-based numbers in order of appearance, deduplicated. Thousands separators and leading
    zeros are normalized, so "1,000" equals "1000" and "09" equals "9"."""
    tokens: list[str] = []
    for match in _NUMBER.finditer(unicodedata.normalize("NFC", text)):
        token = _number_token(match.group())
        if token not in tokens:
            tokens.append(token)
    return tuple(tokens)


def labels(text: str) -> tuple[tuple[str, str], ...]:
    """Each label of `text` as (naming word casefolded, number token), deduplicated."""
    found: list[tuple[str, str]] = []
    for match in _LABEL.finditer(unicodedata.normalize("NFC", text)):
        label = (match.group(1).casefold(), _number_token(match.group(2)))
        if label not in found:
            found.append(label)
    return tuple(found)


def claim_numbers(text: str) -> tuple[str, ...]:
    """Like `number_tokens`, without the numbers that only occur as a label's number: in
    "Phase 4 ran 4 trials" the 4 is still a claim, in "Phase 4 ran" it is not."""
    text = unicodedata.normalize("NFC", text)
    at_label = {match.start(2) for match in _LABEL.finditer(text)}
    tokens: list[str] = []
    for match in _NUMBER.finditer(text):
        token = _number_token(match.group())
        if match.start() not in at_label and token not in tokens:
            tokens.append(token)
    return tuple(tokens)


def hex_ids(text: str) -> tuple[str, ...]:
    """Hash-like hex tokens of `text`, in order, deduplicated (casefolded)."""
    found: list[str] = []
    for match in _HEX_ID.finditer(unicodedata.normalize("NFC", text)):
        token = match.group().casefold()
        if token not in found:
            found.append(token)
    return tuple(found)


def mask_known_ids(text: str, files: Iterable[str]) -> str:
    """`text` with each hash or hex ID that occurs in one of `files` blanked out, so the number
    rules do not read its digits as a claim. Unknown IDs are kept and checked as before."""
    haystack = "\n".join(unicodedata.normalize("NFC", f) for f in files).casefold()
    text = unicodedata.normalize("NFC", text)
    return _HEX_ID.sub(
        lambda m: " " * len(m.group()) if m.group().casefold() in haystack else m.group(), text
    )


def scope_lines(lines: Iterable[str]) -> tuple[int, int] | None:
    """The 1-based line range of a file's own scope statement: the first paragraph within its
    first SCOPE_SEARCH_LINES lines that says what the evidence does not show. None: no such
    paragraph."""
    lines = list(lines)[:SCOPE_SEARCH_LINES]
    start = None
    for number, line in enumerate([*lines, ""], start=1):
        if line.strip() and not line.lstrip().startswith(("#", "|", "```", "---")):
            start = start or number
            continue
        if start is not None:
            paragraph = " ".join(lines[start - 1 : number - 1])
            if _SCOPE.search(_EMPHASIS.sub("", paragraph)):
                return start, number - 1
        start = None
    return None


def label_index(texts: Iterable[str]) -> frozenset[tuple[str, str]]:
    """Every label that appears in `texts` (file lines and paths), for `labels` lookups."""
    return frozenset(label for text in texts for label in labels(text))


def _paragraphs(segments: Iterable[Segment]) -> list[list[Segment]]:
    """The rendered post's paragraphs: a new one at the first segment and at every break."""
    paragraphs: list[list[Segment]] = []
    for index, segment in enumerate(segments):
        if index == 0 or segment.paragraph_break_before:
            paragraphs.append([])
        paragraphs[-1].append(segment)
    return paragraphs


def render_post(segments: Iterable[Segment]) -> str:
    return "\n\n".join(
        " ".join(segment.text for segment in paragraph) for paragraph in _paragraphs(segments)
    )


def check_draft(
    brief: Brief, response: DraftResponse, brief_sha256: str, response_sha256: str
) -> AssertionMap:
    items = brief.contribution.referenceable_items()
    evidence = {segment.id: _evidence(segment, brief, items) for segment in response.segments}
    comparisons = _comparison_findings(response.segments, evidence)
    known = label_index(
        [source.path for source in brief.sources]
        + [line for source in brief.sources for line in source.lines]
    )
    statement = has_statement(brief)
    records = tuple(
        _check_segment(
            segment, brief, evidence[segment.id], comparisons.get(segment.id, []), known, statement
        )
        for segment in response.segments
    )
    questions = tuple(
        CheckedQuestion(
            text=question.text,
            reason=question.reason,
            source_refs=tuple(_check_ref(ref, brief) for ref in question.source_refs),
        )
        for question in response.verification_needed
    )
    post = render_post(response.segments)
    limitation = cites_scope(brief, response) or cites_own_limitation(brief, response)
    document = _document_findings(response, records, questions, post, limitation)
    all_findings = [*document, *(finding for record in records for finding in record.findings)]
    blocking = sum(1 for finding in all_findings if finding.severity == Severity.BLOCKING)
    if not records:
        status = DraftStatus.NO_POST
    else:
        status = DraftStatus.NEEDS_REVISION if blocking else DraftStatus.READY_FOR_REVIEW

    def count(kind: Classification) -> int:
        return sum(1 for record in records if record.classification == kind)

    return AssertionMap(
        draft_status=status,
        brief_sha256=brief_sha256,
        response_sha256=response_sha256,
        generator=response.generator,
        perspective=Perspective(
            author_name=brief.contribution.author_name,
            relationship=brief.contribution.relationship,
        ),
        post_chars=len(post),
        counts=Counts(
            segments=len(records),
            source_referenced=count(Classification.SOURCE_REFERENCED),
            author_stated=count(Classification.AUTHOR_STATED),
            interpretation=count(Classification.INTERPRETATION),
            framing=count(Classification.FRAMING),
            unsupported=count(Classification.UNSUPPORTED),
            blocking=blocking,
            warnings=len(all_findings) - blocking,
        ),
        segments=records,
        document_findings=document,
        verification_needed=questions,
        no_post_reason=response.no_post_reason,
    )


def cites_scope(brief: Brief, response: DraftResponse) -> bool:
    """Whether a segment cites the whole of a file's own scope statement (`scope_lines`): the
    evidence stating its limits counts as a limitation reference."""
    scopes = {source.path: scope_lines(source.lines) for source in brief.sources}
    return any(
        (scope := scopes.get(ref.path)) is not None
        and ref.line_start <= scope[0]
        and scope[1] <= ref.line_end
        and ref.quote is None
        for segment in response.segments
        for ref in segment.source_refs
    )


def cites_own_limitation(brief: Brief, response: DraftResponse) -> bool:
    """Whether a segment cites a limitation the contributor wrote. The tool's own limitation
    items (provenance, revision, roles, owner rule) are for the reviewer and never count."""
    items = brief.contribution.referenceable_items()
    return any(
        ref.startswith("limitations.") and ref in items and not is_tool_item(items[ref])
        for segment in response.segments
        for ref in segment.author_refs
    )


def checked_under_other_rules(stored: AssertionMap, now: AssertionMap) -> bool:
    """Whether `stored` is a self-consistent result of some version of these checks on the same
    brief and response as `now`: every input-derived part equal (texts, bases, citations as
    checked, questions, perspective, digests), only the findings and number tokens different,
    and the classifications, review questions, unlocated numbers, counts and status exactly what
    the stored findings decide. An older checker's map passes; a map edited to say something its own findings do
    not passes nowhere. Without a recorded checker version this is the most a map can show."""
    if stored == now or (
        stored.brief_sha256,
        stored.response_sha256,
        stored.generator,
        stored.perspective,
        stored.post_chars,
        stored.verification_needed,
        stored.no_post_reason,
        len(stored.segments),
    ) != (
        now.brief_sha256,
        now.response_sha256,
        now.generator,
        now.perspective,
        now.post_chars,
        now.verification_needed,
        now.no_post_reason,
        len(now.segments),
    ):
        return False
    questions = {*REVIEW_QUESTIONS.items(), *UNRECORDED_REVIEW_QUESTIONS.items()}
    blocking_total = sum(f.severity == Severity.BLOCKING for f in stored.document_findings)
    findings_total = len(stored.document_findings)
    for old, new in zip(stored.segments, now.segments, strict=True):
        same_inputs = (
            old.id,
            old.paragraph_break_before,
            old.text,
            old.declared_basis,
            old.source_refs,
            old.author_refs,
        ) == (
            new.id,
            new.paragraph_break_before,
            new.text,
            new.declared_basis,
            new.source_refs,
            new.author_refs,
        )
        blocking = sum(f.severity == Severity.BLOCKING for f in old.findings)
        # Number tokenizing is the checker's too (older versions read "SHA-256" as 256): the
        # tokens may differ, but the unlocated ones must be exactly what its finding names.
        unlocated = [n.token for n in old.numbers if not n.located]
        named = [
            token
            for f in old.findings
            if f.code == FindingCode.NUMBER_NOT_IN_EVIDENCE
            for token in (f.detail or "").split(", ")
        ]
        expected = _classify(old.declared_basis, old.findings)
        if (
            not same_inputs
            or old.classification != expected
            or (old.classification, old.review_question) not in questions
            or any(f.segment_id != old.id for f in old.findings)
            or unlocated != named
        ):
            return False
        blocking_total += blocking
        findings_total += len(old.findings)

    def count(kind: Classification) -> int:
        return sum(record.classification == kind for record in stored.segments)

    counts = Counts(
        segments=len(stored.segments),
        source_referenced=count(Classification.SOURCE_REFERENCED),
        author_stated=count(Classification.AUTHOR_STATED),
        interpretation=count(Classification.INTERPRETATION),
        framing=count(Classification.FRAMING),
        unsupported=count(Classification.UNSUPPORTED),
        blocking=blocking_total,
        warnings=findings_total - blocking_total,
    )
    if not stored.segments:
        status = DraftStatus.NO_POST
    else:
        status = DraftStatus.NEEDS_REVISION if blocking_total else DraftStatus.READY_FOR_REVIEW
    return stored.counts == counts and stored.draft_status == status


