"""Deterministic checks of a drafter response against its brief. Pure: no I/O, no model, no NLP.

What the checks establish, and nothing more:
- A source reference is located when the cited file is in the pinned snapshot, the line range
  exists and the quote (if given) appears in those lines after normalization (NFC; Markdown
  emphasis `* _ \\``, blockquote markers and whitespace runs ignored; case-sensitive).
  SOURCE_REFERENCED therefore means "this text is there", never "this sentence is right".
- A drafter's quote is a locator, not evidence. Evidence is the real source text inside the
  located span (or the whole cited range when no quote is given), read with the source's own
  number and word boundaries, plus the segment's cited contributor items.
- Every digit-based number in a segment must appear in that segment's own evidence. A label's
  number ("Phase 4", "Attempt 2") is a name, not a measurement: the label must appear in some
  file of the brief (text or path) instead.
- First person needs a contributor reference, unless the same word is in the located source text.
  Without one it blocks only when the author recorded no statement of their own; otherwise it is
  a warning shown with the statement. When no author is recorded (`UNRECORDED_AUTHOR`, a contribution generated by `story-draft`),
  first person is never attributed, whatever the segment cites.
- A comparison or superlative needs the same phrase in the evidence. It is detected in the
  rendered paragraph, so segment boundaries cannot split it out of view, and it is judged against
  the evidence of every segment it spans.
- Hashtags must be the contributor's; the only permitted link is the snapshot repository URL.
- The tool's reviewer-only items (provenance, revision, roles, owner rule, "nothing recorded")
  are never citable, and the tool's own phrases ("story backlog", "semantic support" ...) block
  unless a cited file uses them; its single words ("backlog", "snapshot" ...) only warn.
- An AUTHOR segment of a recorded author must cite one of the author's own statements. Without
  one it is blocked when it uses first person, otherwise classified INTERPRETATION with a warning.

Blocking findings make the draft NEEDS_REVISION. Style concerns are warnings. Prose is never
rewritten. Semantic support stays UNKNOWN for every segment whatever the outcome.
"""

